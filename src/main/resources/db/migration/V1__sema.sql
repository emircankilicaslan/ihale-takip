-- İhale Takip: temel şema (Oracle 19c+ / 23ai)

CREATE TABLE birim (
    id   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kod  VARCHAR2(20)  NOT NULL UNIQUE,
    ad   VARCHAR2(200) NOT NULL
);

CREATE TABLE kullanici (
    id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kullanici_adi  VARCHAR2(100) NOT NULL UNIQUE,
    ad_soyad       VARCHAR2(200) NOT NULL,
    sifre_hash     VARCHAR2(100),
    rol            VARCHAR2(30)  NOT NULL,
    birim_id       NUMBER(19) REFERENCES birim (id)
);

CREATE TABLE ihale (
    id                    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ihale_no              VARCHAR2(20) UNIQUE,
    ad                    VARCHAR2(300) NOT NULL,
    usul                  VARCHAR2(30)  NOT NULL,
    tur                   VARCHAR2(20)  NOT NULL,
    yaklasik_maliyet      NUMBER(19, 2) NOT NULL,
    birim_id              NUMBER(19) NOT NULL REFERENCES birim (id),
    durum                 VARCHAR2(30)  NOT NULL,
    olusturan_id          NUMBER(19) NOT NULL REFERENCES kullanici (id),
    gerekli_onay_kademesi NUMBER(10),
    onaylayan_id          NUMBER(19) REFERENCES kullanici (id),
    onay_zamani           TIMESTAMP,
    ilan_tarihi           DATE,
    ihale_tarihi          DATE,
    kazanan_teklif_id     NUMBER(19),
    karar_zamani          TIMESTAMP,
    gerekce               VARCHAR2(1000),
    surum                 NUMBER(19) DEFAULT 0 NOT NULL,
    olusturma_zamani      TIMESTAMP NOT NULL,
    CONSTRAINT ck_ihale_maliyet CHECK (yaklasik_maliyet > 0)
);

CREATE INDEX ix_ihale_birim ON ihale (birim_id);
CREATE INDEX ix_ihale_durum ON ihale (durum);

CREATE TABLE teklif (
    id                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ihale_id             NUMBER(19) NOT NULL REFERENCES ihale (id),
    istekli_adi          VARCHAR2(200) NOT NULL,
    vergi_no             VARCHAR2(11)  NOT NULL,
    tutar                NUMBER(19, 2) NOT NULL,
    durum                VARCHAR2(20)  NOT NULL,
    ret_gerekcesi        VARCHAR2(1000),
    asiri_dusuk_aciklama VARCHAR2(10),
    olusturma_zamani     TIMESTAMP NOT NULL,
    CONSTRAINT uq_teklif_istekli UNIQUE (ihale_id, vergi_no),
    CONSTRAINT ck_teklif_tutar CHECK (tutar > 0)
);

ALTER TABLE ihale ADD CONSTRAINT fk_ihale_kazanan FOREIGN KEY (kazanan_teklif_id) REFERENCES teklif (id);

CREATE TABLE resmi_tatil (
    tarih DATE PRIMARY KEY,
    ad    VARCHAR2(100) NOT NULL
);

CREATE TABLE denetim_kaydi (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zaman         TIMESTAMP NOT NULL,
    kullanici_adi VARCHAR2(100) NOT NULL,
    islem         VARCHAR2(50)  NOT NULL,
    varlik_turu   VARCHAR2(30)  NOT NULL,
    varlik_id     NUMBER(19),
    ayrinti       VARCHAR2(2000)
);

CREATE INDEX ix_denetim_varlik ON denetim_kaydi (varlik_turu, varlik_id);
